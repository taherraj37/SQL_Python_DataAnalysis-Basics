"""
generate_dummy_data.py
----------------------
Creates a realistic (and intentionally *messy*) dummy dataset for a fictional
sales & marketing company, "Northwind Growth Co.".

Output CSVs (written to data/raw/):
    customers.csv   - customer master data
    products.csv    - product catalogue
    campaigns.csv   - marketing campaigns
    leads.csv       - marketing leads generated by campaigns
    sales.csv       - sales order lines

Data-quality problems are injected on purpose so the cleaning / validation
scripts have something to fix:
    * duplicate rows and duplicate business keys
    * leading/trailing whitespace and inconsistent casing
    * mixed date formats and some unparseable dates
    * currency values stored as text ("$1,234.50")
    * missing values, invalid emails, negative quantities, outliers

Usage:
    python data/generate_dummy_data.py
"""
from pathlib import Path

import numpy as np
import pandas as pd

SEED = 42
rng = np.random.default_rng(SEED)
OUT_DIR = Path(__file__).resolve().parent / "raw"
OUT_DIR.mkdir(parents=True, exist_ok=True)

N_CUSTOMERS, N_PRODUCTS, N_CAMPAIGNS, N_LEADS, N_SALES = 500, 40, 24, 3000, 6000
START, END = pd.Timestamp("2024-01-01"), pd.Timestamp("2025-12-31")

REGIONS = ["North", "South", "East", "West", "Central"]
SEGMENTS = ["Enterprise", "SMB", "Consumer"]
CHANNELS = ["Online", "Retail", "Partner", "Direct Sales"]
CAMPAIGN_TYPES = ["Email", "Paid Search", "Social Media", "Webinar", "Trade Show", "Content"]
LEAD_SOURCES = ["Website", "Referral", "LinkedIn", "Google Ads", "Event", "Cold Call"]
SALES_REPS = ["A. Patel", "B. Nguyen", "C. Smith", "D. Garcia", "E. Chen", "F. Martin"]
FIRST = ["Olivia", "Liam", "Emma", "Noah", "Ava", "Lucas", "Mia", "Ethan", "Zoe", "Arjun",
         "Sofia", "Mateo", "Chloe", "Ryan", "Priya", "Daniel", "Grace", "Omar", "Leah", "Jack"]
LAST = ["Smith", "Brown", "Tremblay", "Martin", "Roy", "Wilson", "Lee", "Singh", "Gagnon",
        "Taylor", "Campbell", "Anderson", "Kumar", "Wong", "Clark", "Lewis"]
CITIES = {"North": ["Sudbury", "Thunder Bay"], "South": ["Windsor", "London"],
          "East": ["Ottawa", "Montreal"], "West": ["Vancouver", "Calgary"],
          "Central": ["Toronto", "Mississauga"]}


def random_dates(n, start=START, end=END):
    span = (end - start).days
    return start + pd.to_timedelta(rng.integers(0, span + 1, n), unit="D")


def messy_date_strings(dates, error_rate=0.03):
    """Render dates in mixed formats, with a few garbage values."""
    fmts = ["%Y-%m-%d", "%m/%d/%Y", "%d-%b-%Y", "%Y/%m/%d"]
    out = []
    for d in dates:
        r = rng.random()
        if r < error_rate:
            out.append(rng.choice(["", "N/A", "31/31/2024", "TBD"]))
        else:
            out.append(d.strftime(fmts[rng.choice(len(fmts), p=[0.7, 0.15, 0.1, 0.05])]))
    return out


def dirty_text(series, rate=0.08):
    """Randomly add whitespace / change casing."""
    s = series.copy().astype(object)
    idx = rng.random(len(s)) < rate
    ops = [lambda x: f"  {x} ", str.upper, str.lower, lambda x: f"{x}  "]
    s[idx] = [ops[rng.integers(len(ops))](v) for v in s[idx]]
    return s


# --------------------------------------------------------------------------- #
# Customers
# --------------------------------------------------------------------------- #
regions = rng.choice(REGIONS, N_CUSTOMERS)
first = rng.choice(FIRST, N_CUSTOMERS)
last = rng.choice(LAST, N_CUSTOMERS)
emails = [f"{f.lower()}.{l.lower()}{i}@example.com" for i, (f, l) in enumerate(zip(first, last))]
bad_email_idx = rng.choice(N_CUSTOMERS, 25, replace=False)
for i in bad_email_idx:
    emails[i] = rng.choice([emails[i].replace("@", ""), "", "unknown", emails[i].replace(".com", "")])

customers = pd.DataFrame({
    "customer_id": [f"C{i:05d}" for i in range(1, N_CUSTOMERS + 1)],
    "first_name": dirty_text(pd.Series(first)),
    "last_name": dirty_text(pd.Series(last)),
    "email": emails,
    "phone": [f"({rng.integers(200, 999)}) {rng.integers(200, 999)}-{rng.integers(1000, 9999)}"
              if rng.random() > 0.05 else "" for _ in range(N_CUSTOMERS)],
    "city": [rng.choice(CITIES[r]) for r in regions],
    "region": dirty_text(pd.Series(regions), rate=0.1),
    "segment": rng.choice(SEGMENTS, N_CUSTOMERS, p=[0.2, 0.45, 0.35]),
    "signup_date": messy_date_strings(random_dates(N_CUSTOMERS, pd.Timestamp("2021-01-01"), END)),
})
# exact duplicate rows + duplicated keys with conflicting data
customers = pd.concat([customers, customers.sample(12, random_state=SEED)], ignore_index=True)
dup_key = customers.sample(5, random_state=7).copy()
dup_key["city"] = "Toronto"
customers = pd.concat([customers, dup_key], ignore_index=True)

# --------------------------------------------------------------------------- #
# Products
# --------------------------------------------------------------------------- #
CATEGORIES = {
    "Software": ["CRM Suite", "Email Automation", "Analytics Pro", "SEO Toolkit", "Social Scheduler"],
    "Services": ["Onboarding Package", "Consulting Hour", "Campaign Setup", "Training Day"],
    "Hardware": ["POS Terminal", "Barcode Scanner", "Display Kiosk"],
    "Subscriptions": ["Basic Plan", "Growth Plan", "Enterprise Plan"],
}
rows = []
pid = 1
for cat, names in CATEGORIES.items():
    for name in names:
        for tier in ["Standard", "Plus", "Premium"]:
            if pid > N_PRODUCTS:
                break
            base = {"Software": 400, "Services": 150, "Hardware": 900, "Subscriptions": 60}[cat]
            price = round(base * {"Standard": 1, "Plus": 1.6, "Premium": 2.5}[tier] * rng.uniform(0.85, 1.15), 2)
            rows.append({"product_id": f"P{pid:04d}", "product_name": f"{name} {tier}",
                         "category": cat, "unit_cost": round(price * rng.uniform(0.35, 0.7), 2),
                         "list_price": f"${price:,.2f}" if rng.random() < 0.3 else price})
            pid += 1
products = pd.DataFrame(rows)
products.loc[rng.choice(len(products), 2, replace=False), "unit_cost"] = np.nan

# --------------------------------------------------------------------------- #
# Campaigns
# --------------------------------------------------------------------------- #
c_start = random_dates(N_CAMPAIGNS, START, pd.Timestamp("2025-10-31"))
campaigns = pd.DataFrame({
    "campaign_id": [f"CMP{i:03d}" for i in range(1, N_CAMPAIGNS + 1)],
    "campaign_name": [f"{t} - {s.strftime('%b %Y')}" for t, s in
                      zip(rng.choice(CAMPAIGN_TYPES, N_CAMPAIGNS), c_start)],
    "campaign_type": rng.choice(CAMPAIGN_TYPES, N_CAMPAIGNS),
    "start_date": c_start.strftime("%Y-%m-%d"),
    "end_date": (c_start + pd.to_timedelta(rng.integers(14, 90, N_CAMPAIGNS), unit="D")).strftime("%Y-%m-%d"),
    "budget": rng.integers(5, 80, N_CAMPAIGNS) * 1000,
    "target_region": rng.choice(REGIONS + ["All"], N_CAMPAIGNS),
})
campaigns["campaign_type"] = campaigns["campaign_name"].str.split(" - ").str[0]
# one campaign whose end date is before its start date
campaigns.loc[3, ["start_date", "end_date"]] = campaigns.loc[3, ["end_date", "start_date"]].values

# --------------------------------------------------------------------------- #
# Leads
# --------------------------------------------------------------------------- #
lead_dates = random_dates(N_LEADS)
converted = rng.random(N_LEADS) < 0.22
leads = pd.DataFrame({
    "lead_id": [f"L{i:06d}" for i in range(1, N_LEADS + 1)],
    "campaign_id": rng.choice(campaigns["campaign_id"], N_LEADS),
    "lead_source": dirty_text(pd.Series(rng.choice(LEAD_SOURCES, N_LEADS)), rate=0.05),
    "created_date": messy_date_strings(lead_dates, error_rate=0.01),
    "lead_score": np.where(rng.random(N_LEADS) < 0.04, np.nan, rng.integers(1, 101, N_LEADS)),
    "status": np.where(converted, "Converted", rng.choice(["Open", "Qualified", "Lost"], N_LEADS)),
    "customer_id": np.where(converted, rng.choice(customers["customer_id"].unique(), N_LEADS), ""),
})
leads = pd.concat([leads, leads.sample(30, random_state=SEED)], ignore_index=True)

# --------------------------------------------------------------------------- #
# Sales (order lines)
# --------------------------------------------------------------------------- #
order_dates = random_dates(N_SALES)
prod_idx = rng.integers(0, len(products), N_SALES)
prices = pd.to_numeric(products["list_price"].astype(str).str.replace(r"[$,]", "", regex=True))
qty = rng.integers(1, 20, N_SALES)
qty[rng.choice(N_SALES, 20, replace=False)] *= -1                         # invalid negatives
qty[rng.choice(N_SALES, 8, replace=False)] = rng.integers(500, 2000, 8)  # outliers
discount = rng.choice([0, 0, 0, 0.05, 0.1, 0.15, 0.2], N_SALES)
discount[rng.choice(N_SALES, 6, replace=False)] = 1.5                     # invalid > 100%
cust_ids = rng.choice(customers["customer_id"].unique(), N_SALES).astype(object)
cust_ids[rng.choice(N_SALES, 15, replace=False)] = "C99999"               # orphan FK

sales = pd.DataFrame({
    "order_id": [f"SO{i:07d}" for i in range(1, N_SALES + 1)],
    "order_date": messy_date_strings(order_dates, error_rate=0.01),
    "customer_id": cust_ids,
    "product_id": products["product_id"].values[prod_idx],
    "campaign_id": np.where(rng.random(N_SALES) < 0.4, rng.choice(campaigns["campaign_id"], N_SALES), ""),
    "quantity": qty,
    "unit_price": [f"${p:,.2f}" if rng.random() < 0.1 else round(p, 2) for p in prices.values[prod_idx]],
    "discount": discount,
    "channel": dirty_text(pd.Series(rng.choice(CHANNELS, N_SALES, p=[0.4, 0.2, 0.15, 0.25])), rate=0.06),
    "sales_rep": rng.choice(SALES_REPS + [""], N_SALES, p=[0.16] * 6 + [0.04]),
    "status": rng.choice(["Completed", "Completed", "Completed", "Returned", "Cancelled", "completed "], N_SALES),
})
sales = pd.concat([sales, sales.sample(40, random_state=SEED)], ignore_index=True)
sales = sales.sample(frac=1, random_state=SEED).reset_index(drop=True)

for name, df in {"customers": customers, "products": products, "campaigns": campaigns,
                 "leads": leads, "sales": sales}.items():
    path = OUT_DIR / f"{name}.csv"
    df.to_csv(path, index=False)
    print(f"wrote {len(df):>6,} rows -> {path.relative_to(OUT_DIR.parent.parent)}")
